const tables = { ru, en };

export const UI_KEYS = Object.keys(ru);

export const LANGS = ['uk', 'ru', 'en'];

export function readLang() {
  try {
    const saved = localStorage.getItem('edwic-lang');
    if (LANGS.includes(saved)) return saved;
  } catch {
    /* private mode */
  }
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'uk').toLowerCase();
  if (nav.startsWith('ru')) return 'ru';
  if (nav.startsWith('en')) return 'en';
  return 'uk';
}

export function writeLang(lang) {
  try {
    localStorage.setItem('edwic-lang', lang);
  } catch {
    /* ignore */
  }
}

export function translate(lang, text, vars) {
  if (text == null) return '';
  const source = String(text);
  const table = tables[lang];
  let out = table?.[source] ?? source;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, value == null ? '' : String(value));
    }
  }
  return out;
}

export function placeholders(text) {
  return [...String(text).matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map((match) => match[1]).sort();
}

export function samePlaceholders(source, translated) {
  const a = placeholders(source).join(',');
  return a === placeholders(translated).join(',');
}
